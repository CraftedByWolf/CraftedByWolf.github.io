function planDayInfo(now = new Date()) {
  const start = new Date(PLAN_START + "T00:00:00");
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  const dayIdx = Math.floor((today - start) / 86400000);
  const totalDays = PLAN_WEEKS * 7;
  const before = dayIdx < 0, after = dayIdx >= totalDays;
  const clamped = Math.max(0, Math.min(totalDays - 1, dayIdx));
  const weekNo = Math.floor(clamped / 7) + 1;
  const dow = clamped % 7; // 0 = Monday
  const week = WEEKS[weekNo - 1];
  const phase = PHASES.find(p => p.id === week.phase);
  let ai, dsa, kind;
  if (dow < 5) { kind = "weekday"; ai = week.ai.days[dow]; dsa = week.dsa.days[dow]; }
  else if (dow === 5) { kind = "saturday"; ai = "Project: " + week.ai.project; dsa = "Re-solve this week's hardest " + week.dsa.title.replace(/^A2Z /, "") + " problems"; }
  else { kind = "sunday"; ai = "Revise: " + week.ai.title; dsa = "Contest / timed mock, then review mistakes"; }
  return { before, after, dayIdx, totalDays, weekNo, dow, week, phase, ai, dsa, sql: week.sql, kind,
    daysLeft: Math.max(0, totalDays - Math.max(0, dayIdx)) };
}

function planEndDate() { const d = new Date(PLAN_START + "T00:00:00"); d.setDate(d.getDate() + PLAN_WEEKS * 7 - 1); return d; }

